const { withAppBuildGradle, withDangerousMod, withXcodeProject } = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

// ---------------------------------------------------------------------------
// Links app-owned Everysight glasses screens into the native build and
// generates their registration with the bridge's EvsScreenRegistry.
//
// App screens live in app source (committed), e.g.:
//
//   <app>/evs-screens/ios/HelloWorldScreen.swift
//   <app>/evs-screens/android/HelloWorldScreen.kt
//
// Usage in app.config.ts:
//
//   plugins: [
//     ['react-native-evskit', {
//       bundleResources: ['./sdk.key'],
//       screens: {
//         ios: './evs-screens/ios',
//         android: './evs-screens/android',
//         // id -> class name. Swift: class name in the app target.
//         // Kotlin: fully-qualified class name.
//         register: {
//           'hello-world': {
//             ios: 'HelloWorldScreen',
//             android: 'com.sampleevskitproject.screens.HelloWorldScreen',
//           },
//         },
//       },
//     }],
//   ]
//
// On `expo prebuild` this:
// - iOS: adds each app-owned .swift file to the app target's Sources phase
//   (path relative to ios/, e.g. "../evs-screens/ios/HelloWorldScreen.swift"),
//   and writes a generated `ios/EvsAppScreens.generated.swift` that registers
//   every id. The generated file self-registers via top-level statements, so
//   no AppDelegate changes are needed.
// - Android: registers the app-owned dir (plus a generated dir) as extra
//   sourceSets java srcDirs, and writes a generated registrar object. The
//   bridge loads it via Class.forName on startup (no-op when absent).
//
// The source of truth is the committed evs-screens/ folder plus the config,
// and the plugin re-runs on every prebuild, so wiping ios/ + android/ loses
// nothing. Push from JS with `await EvsScreens.show("hello-world")`.
// ---------------------------------------------------------------------------
const GENERATED_IOS_FILE = "EvsAppScreens.generated.swift";
const GENERATED_ANDROID_DIR = "evs-screens-generated";
const GENERATED_ANDROID_PACKAGE = "evs.screens.generated";
const GENERATED_ANDROID_CLASS = "EvsAppScreensGenerated";

function withEvsScreens(config, { screens = {} } = {}) {
  const { ios: iosDir, android: androidDir, register = {} } = screens;
  if (!iosDir && !androidDir) {
    return config;
  }
  if (iosDir) {
    config = withEvsIosScreens(config, iosDir, register);
  }
  if (androidDir) {
    config = withEvsAndroidScreens(config, androidDir, register);
  }
  return config;
}

function listSourceFiles(absDir, ext) {
  if (!fs.existsSync(absDir) || !fs.statSync(absDir).isDirectory()) {
    return [];
  }
  return fs.readdirSync(absDir).filter((f) => f.endsWith(ext)).sort();
}

function toPosix(p) {
  return p.split(path.sep).join("/");
}

function sanitize(id) {
  return id.replace(/[^A-Za-z0-9_]/g, "_");
}

module.exports = withEvsScreens;
function generatedIosContents(register) {
  const lines = [
    "// Generated by react-native-evskit — do not edit.",
    "// Registers app-owned screens (see `screens.register` in app.config).",
    "",
    "import NativeEvsKit",
    "import RNEvsKit",
    "",
  ];
  for (const [id, entry] of Object.entries(register)) {
    const className = typeof entry === "string" ? entry : entry.ios;
    if (!className) {
      continue;
    }
    lines.push(
      `private let _evsRegister_${sanitize(id)}: Void = {`,
      `  EvsScreenRegistry.register(id: ${JSON.stringify(id)}) { ${className}() }`,
      `}()`,
      "",
    );
  }
  if (!Object.keys(register).length) {
    lines.push("// No screens registered.", "");
  }
  return lines.join("\n");
}

function addSwiftFileToSources(project, objects, sourcesPhase, fileName, relativePath) {
  const alreadyAdded = Object.keys(objects.PBXBuildFile).some(
    (key) =>
      !key.endsWith("_comment") &&
      objects.PBXBuildFile[key].fileRef_comment === fileName,
  );
  if (alreadyAdded) {
    return;
  }
  const fileRefUuid = project.generateUuid();
  objects.PBXFileReference[fileRefUuid] = {
    isa: "PBXFileReference",
    explicitFileType: "sourcecode.swift",
    fileEncoding: 4,
    name: fileName,
    path: relativePath,
    // Quotes must be embedded: the `xcode` lib's pbxWriter does not add
    // quotes itself, and angle brackets (<>) are invalid unquoted.
    sourceTree: '"<group>"',
  };
  objects.PBXFileReference[`${fileRefUuid}_comment`] = fileName;
  const buildFileUuid = project.generateUuid();
  objects.PBXBuildFile[buildFileUuid] = {
    isa: "PBXBuildFile",
    fileRef: fileRefUuid,
    fileRef_comment: fileName,
  };
  objects.PBXBuildFile[`${buildFileUuid}_comment`] =
    `${fileName} in Sources`;
  sourcesPhase.files = sourcesPhase.files || [];
  sourcesPhase.files.push({
    value: buildFileUuid,
    comment: `${fileName} in Sources`,
  });
}

function withEvsIosScreens(config, iosScreensDir, register) {
  return withXcodeProject(config, (config) => {
    const projectRoot = config.modRequest.projectRoot;
    const absDir = path.join(projectRoot, iosScreensDir);
    const files = listSourceFiles(absDir, ".swift");
    const project = config.modResults;
    const objects = project.hash.project.objects;
    objects.PBXBuildFile = objects.PBXBuildFile || {};
    objects.PBXFileReference = objects.PBXFileReference || {};
    const target = project.getFirstTarget();
    const nativeTarget = objects.PBXNativeTarget[target.uuid];
    const sourcesPhaseUuid = nativeTarget.buildPhases.find((phase) =>
      /Sources/i.test(phase.comment || ""),
    )?.value;
    const sourcesPhase = sourcesPhaseUuid
      ? objects.PBXSourcesBuildPhase[sourcesPhaseUuid]
      : undefined;
    if (!sourcesPhase) {
      return config;
    }
    // The Xcode project lives in <projectRoot>/ios, so file reference paths
    // must be relative to that directory (e.g. "../evs-screens/ios/X.swift").
    const iosDir = path.join(projectRoot, "ios");
    for (const fileName of files) {
      addSwiftFileToSources(
        project,
        objects,
        sourcesPhase,
        fileName,
        toPosix(path.join(path.relative(iosDir, absDir), fileName)),
      );
    }
    // Generated registrar — written into the (regenerable) ios/ dir and
    // linked the same way. Top-level `let` runs at binary load, so no
    // AppDelegate changes are needed.
    if (Object.keys(register).length) {
      const generatedPath = path.join(iosDir, GENERATED_IOS_FILE);
      fs.writeFileSync(generatedPath, generatedIosContents(register));
      addSwiftFileToSources(
        project,
        objects,
        sourcesPhase,
        GENERATED_IOS_FILE,
        GENERATED_IOS_FILE,
      );
    }
    return config;
  });
}
function generatedAndroidContents(register) {
  const lines = [
    `package ${GENERATED_ANDROID_PACKAGE}`,
    "",
    "// Generated by react-native-evskit — do not edit.",
    "// Registers app-owned screens (see `screens.register` in app.config).",
    "// Loaded via Class.forName from the bridge module's OnCreate.",
    "",
    "import expo.modules.evskit.EvsScreenRegistry",
    "",
    `object ${GENERATED_ANDROID_CLASS} {`,
    "  init {",
  ];
  for (const [id, entry] of Object.entries(register)) {
    const fqcn = typeof entry === "string" ? entry : entry.android;
    if (!fqcn) {
      continue;
    }
    const simple = fqcn.split(".").pop();
    lines.push(`import ${fqcn}`);
    lines.push(`    EvsScreenRegistry.register(${JSON.stringify(id)}) { ${simple}() }`);
  }
  lines.push("  }", "}");
  return lines.join("\n");
}

function withEvsAndroidScreens(config, androidScreensDir, register) {
  // NOTE: config.modRequest only exists inside a mod callback — never read
  // projectRoot at the outer plugin level (it is undefined there and crashes
  // prebuild with "Cannot read properties of undefined").
  const hasRegister = Object.keys(register).length > 0;

  // Write the generated registrar into a disposable dir under android/.
  // withDangerousMod runs after the native project exists, so ios/android
  // dirs are present and modRequest.projectRoot is available.
  if (hasRegister) {
    config = withDangerousMod(config, [
      "android",
      (config) => {
        const projectRoot = config.modRequest.projectRoot;
        const genDir = path.join(projectRoot, "android", GENERATED_ANDROID_DIR);
        fs.mkdirSync(genDir, { recursive: true });
        fs.writeFileSync(
          path.join(genDir, `${GENERATED_ANDROID_CLASS}.kt`),
          generatedAndroidContents(register),
        );
        return config;
      },
    ]);
  }

  // Register the app-owned screens dir (+ generated dir) as extra java
  // srcDirs so their .kt files compile into the app.
  config = withAppBuildGradle(config, (config) => {
    const projectRoot = config.modRequest.projectRoot;
    const marker = "// react-native-evskit: app-owned glasses screens";
    if (config.modResults.contents.includes(marker)) {
      return config;
    }
    // Paths relative to <projectRoot>/android/app.
    const appDir = path.join(projectRoot, "android", "app");
    const srcDirs = [toPosix(path.relative(appDir, path.join(projectRoot, androidScreensDir)))];
    if (hasRegister) {
      srcDirs.push(
        toPosix(path.relative(appDir, path.join(projectRoot, "android", GENERATED_ANDROID_DIR))),
      );
    }
    const srcDirsList = srcDirs.map((d) => `                '${d}'`).join(",\n");
    config.modResults.contents = config.modResults.contents.replace(
      /android\s*\{/,
      `android {\n${marker}\n    sourceSets {\n        main {\n            java.srcDirs += [\n${srcDirsList}\n            ]\n        }\n    }`,
    );
    return config;
  });
  return config;
}
